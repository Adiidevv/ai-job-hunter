CREATE TABLE IF NOT EXISTS users (
 id BIGSERIAL PRIMARY KEY, name VARCHAR(120) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE,
 password_hash TEXT NOT NULL, desired_roles TEXT NOT NULL DEFAULT '', preferred_location TEXT NOT NULL DEFAULT 'Remote, India',
 email_alerts BOOLEAN NOT NULL DEFAULT FALSE, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS cvs (
 id BIGSERIAL PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 original_name TEXT NOT NULL, stored_name TEXT NOT NULL, mime_type TEXT NOT NULL, size_bytes BIGINT NOT NULL,
 extracted_text TEXT NOT NULL DEFAULT '', extracted_skills TEXT[] NOT NULL DEFAULT '{}',
 extraction_status VARCHAR(40) NOT NULL DEFAULT 'pending', extraction_message TEXT NOT NULL DEFAULT '', uploaded_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
CREATE TABLE IF NOT EXISTS jobs (
 id BIGSERIAL PRIMARY KEY, source VARCHAR(80) NOT NULL, source_job_id TEXT NOT NULL,
 title TEXT NOT NULL, company TEXT NOT NULL, location TEXT NOT NULL DEFAULT 'Not specified',
 job_type TEXT NOT NULL DEFAULT 'Not specified', description TEXT NOT NULL DEFAULT '', skills TEXT[] NOT NULL DEFAULT '{}',
 apply_url TEXT NOT NULL, posted_at TIMESTAMPTZ, source_url TEXT NOT NULL DEFAULT '', last_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), UNIQUE(source, source_job_id)
);
CREATE TABLE IF NOT EXISTS applications (
 id BIGSERIAL PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 job_id BIGINT NOT NULL REFERENCES jobs(id) ON DELETE CASCADE, status VARCHAR(40) NOT NULL DEFAULT 'saved',
 notes TEXT NOT NULL DEFAULT '', applied_at TIMESTAMPTZ, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
 UNIQUE(user_id, job_id)
);
CREATE TABLE IF NOT EXISTS alert_history (
 id BIGSERIAL PRIMARY KEY, user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 job_id BIGINT NOT NULL REFERENCES jobs(id) ON DELETE CASCADE, sent_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), UNIQUE(user_id, job_id)
);
CREATE INDEX IF NOT EXISTS idx_cvs_user_id ON cvs(user_id);
CREATE INDEX IF NOT EXISTS idx_applications_user_id ON applications(user_id);
CREATE INDEX IF NOT EXISTS idx_jobs_posted_at ON jobs(posted_at DESC);
ALTER TABLE users ADD COLUMN IF NOT EXISTS email_alerts BOOLEAN NOT NULL DEFAULT FALSE;
ALTER TABLE jobs ADD COLUMN IF NOT EXISTS source_url TEXT NOT NULL DEFAULT '';
ALTER TABLE jobs ADD COLUMN IF NOT EXISTS last_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW();
ALTER TABLE cvs ADD COLUMN IF NOT EXISTS extracted_text TEXT NOT NULL DEFAULT '';
ALTER TABLE cvs ADD COLUMN IF NOT EXISTS extracted_skills TEXT[] NOT NULL DEFAULT '{}';
ALTER TABLE cvs ADD COLUMN IF NOT EXISTS extraction_status VARCHAR(40) NOT NULL DEFAULT 'pending';
ALTER TABLE cvs ADD COLUMN IF NOT EXISTS extraction_message TEXT NOT NULL DEFAULT '';
CREATE TABLE IF NOT EXISTS job_feed_meta (
 meta_key TEXT PRIMARY KEY,
 meta_value TEXT NOT NULL,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);
